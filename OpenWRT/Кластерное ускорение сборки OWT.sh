distccd — это серверная часть инструмента distcc (distributed C compiler):
 она принимает задачи компиляции от клиента и запускает на своей машине gcc/g++ 
 для их выполнения. Учитывая, что вы собирали кластер на Linux‑машинах и 
 интересовались ускорением сборки OpenWrt/ядер — это как раз нужный компонент
 для второй машины.
sudo apt install distcc

Как запустить distccd (сервер)
На «второй» машине (192.168.1.201) запустите демон с разрешением на приём задач из вашей подсети:

bash
sudo distccd --daemon --allow 192.168.1.0/24 --port 3632
Ключевые опции:

--daemon — запуск в фоне (как демон).
--allow — разрешённые IP/подсети. Для двух ваших машин хватит 192.168.1.0/24.
--port — порт по умолчанию 3632, можно не указывать.
Если хотите логировать, добавьте --log-file /var/log/distccd.log --log-level info.

Автозапуск (systemd)
После установки обычно появляется юнит distccd.service. Включите и запустите:

bash
sudo systemctl enable distccd
sudo systemctl start distccd
Если в вашем дистрибутиве нет готового юнита — можно создать свой или запускать вручную/через cron/supervisor.

Настройка клиента (ваша основная машина, 192.168.1.200)
На основной машине достаточно выставить переменную окружения с хостами:

bash
export DISTCC_HOSTS="192.168.1.201"
export PATH="/usr/lib/distcc:$PATH"   # важно: distcc должен быть раньше gcc в PATH
Затем запускайте сборку через make с обёрткой компилятора:

bash
make CC="distcc gcc" CXX="distcc g++" -j$(nproc)
Или, если проект сам подхватывает CC из окружения:

bash
CC="distcc gcc" CXX="distcc g++" make -j$(nproc)
Важные требования и нюансы
Одинаковые компиляторы. На обеих машинах версии gcc/g++ должны совпадать (или быть очень близкими), иначе возможны ошибки линковки и несовместимость объектных файлов.
Заголовки и include‑пути. distcc передаёт на сервер уже препроцессированный код, поэтому на сервере не нужны те же самые заголовочные файлы, но системные библиотеки и ABI должны быть совместимы.
Сеть. Нужен открытый порт 3632 между машинами. Проверьте фаервол:
bash
sudo ufw allow 3632/tcp
# или iptables/nftables по вашей схеме
Безопасность. distcc не шифрует трафик и не имеет сложной аутентификации. Используйте только в доверенной локальной сети (как у вас).
Комбинирование с ccache. На каждой машине можно и нужно ставить ccache и использовать вместе с distcc:
bash
export CC="ccache gcc"
export CXX="ccache g++"
# затем сборка через distcc как выше
Тогда на каждом узле будет локальный кэш компиляции, а задачи будут распределяться между машинами.
Проверка работы
На клиенте запустите тестовую компиляцию:

bash
echo 'int main(){return 0;}' | distcc gcc -x c - -o test_distcc
./test_distcc && echo "OK" || echo "FAIL"
Также можно посмотреть статистику: distccmon-text 1 (выводит в реальном времени, какие хосты используются).




